"use client";

import { useState, useEffect, useCallback } from "react";
import {
  Wallet,
  CheckCircle2,
  AlertTriangle,
  RefreshCw,
  Send,
  ArrowUpRight,
  ShieldCheck,
  Building,
  Clock,
  FileSpreadsheet,
  AlertCircle,
  Loader2,
  DollarSign,
  ChevronRight,
  TrendingUp,
  Receipt,
  Layers,
} from "lucide-react";
import { AdminLayout } from "@/components/admin/AdminLayout";
import { useAuth } from "@/context/AuthContext";
import { formatPrice } from "@/lib/utils";
import {
  FinancialLedgerReport,
  PayoutBatchItem,
  getFinancialLedger,
  getPayoutBatches,
  generatePayoutBatch,
  executePayoutBatch,
} from "@/lib/admin/payouts";

export default function AdminPayoutsPage() {
  const { token, isSuperAdmin } = useAuth();

  const [ledger, setLedger] = useState<FinancialLedgerReport | null>(null);
  const [batches, setBatches] = useState<PayoutBatchItem[]>([]);
  const [totalBatches, setTotalBatches] = useState(0);

  const [isLoading, setIsLoading] = useState(true);
  const [isRefreshing, setIsRefreshing] = useState(false);
  const [isGenerating, setIsGenerating] = useState(false);
  const [executingBatchId, setExecutingBatchId] = useState<string | null>(null);

  const [notice, setNotice] = useState<{ type: "success" | "error"; message: string } | null>(null);
  const [selectedBatch, setSelectedBatch] = useState<PayoutBatchItem | null>(null);

  const loadData = useCallback(async (isRefresh = false) => {
    if (!token) return;
    if (isRefresh) setIsRefreshing(true);
    else setIsLoading(true);

    try {
      const [ledgerData, batchesData] = await Promise.all([
        getFinancialLedger(token),
        getPayoutBatches(token, 1, 20),
      ]);

      if (ledgerData) setLedger(ledgerData);
      if (batchesData) {
        setBatches(batchesData.batches || []);
        setTotalBatches(batchesData.total || 0);
      }
    } catch (err: any) {
      console.error("Failed to load payout & ledger data:", err);
      setNotice({
        type: "error",
        message: err.message || "Failed to load financial records",
      });
    } finally {
      setIsLoading(false);
      setIsRefreshing(false);
    }
  }, [token]);

  useEffect(() => {
    loadData();
  }, [loadData]);

  // Handle generating a new batch from cleared orders
  async function handleGenerateBatch() {
    if (!token || !isSuperAdmin) return;
    setIsGenerating(true);
    setNotice(null);

    try {
      const newBatch = await generatePayoutBatch(token, {
        minPayoutAmount: 20,
        notes: `Automated MoMo settlement batch generated by Admin on ${new Date().toLocaleDateString()}`,
      });

      if (newBatch) {
        setNotice({
          type: "success",
          message: `Payout batch ${newBatch.batchReference} generated successfully for GHS ${Number(newBatch.totalAmount).toFixed(2)} across ${newBatch.totalVendors} merchants.`,
        });
        await loadData(true);
      }
    } catch (err: any) {
      setNotice({
        type: "error",
        message: err.message || "Failed to generate payout batch",
      });
    } finally {
      setIsGenerating(false);
    }
  }

  // Handle executing batch transfer via Paystack
  async function handleExecuteBatch(batchId: string) {
    if (!token || !isSuperAdmin) return;
    setExecutingBatchId(batchId);
    setNotice(null);

    try {
      const res = await executePayoutBatch(token, batchId);
      setNotice({
        type: "success",
        message: res.message || "Payout batch submitted for MoMo disbursement via Paystack.",
      });
      await loadData(true);
    } catch (err: any) {
      setNotice({
        type: "error",
        message: err.message || "Failed to execute payout batch",
      });
    } finally {
      setExecutingBatchId(null);
    }
  }

  return (
    <AdminLayout
      title="Financial Reconciliation & Payouts"
      actions={
        <div className="flex items-center gap-2">
          <button
            type="button"
            onClick={() => loadData(true)}
            disabled={isLoading || isRefreshing}
            className="flex items-center gap-1.5 rounded-lg border border-zinc-200 bg-white px-3 py-1.5 text-xs font-semibold text-zinc-700 shadow-sm transition hover:bg-zinc-50 disabled:opacity-60"
          >
            <RefreshCw
              className={`h-3.5 w-3.5 text-zinc-500 ${isRefreshing ? "animate-spin text-[#ff9900]" : ""}`}
            />
            <span>Refresh</span>
          </button>

          {isSuperAdmin && (
            <button
              type="button"
              onClick={handleGenerateBatch}
              disabled={isGenerating || isLoading}
              className="flex items-center gap-1.5 rounded-lg bg-[#ff9900] px-3.5 py-1.5 text-xs font-bold text-zinc-950 shadow-sm transition hover:bg-[#e68a00] active:scale-95 disabled:opacity-50"
            >
              {isGenerating ? (
                <Loader2 className="h-3.5 w-3.5 animate-spin" />
              ) : (
                <Wallet className="h-3.5 w-3.5" />
              )}
              <span>Generate Payout Batch</span>
            </button>
          )}
        </div>
      }
    >
      {/* Alert Notices */}
      {notice && (
        <div
          className={`mb-6 flex items-start gap-3 rounded-xl border p-4 shadow-sm animate-in fade-in duration-200 ${
            notice.type === "success"
              ? "border-emerald-200 bg-emerald-50/70 text-emerald-900"
              : "border-red-200 bg-red-50/70 text-red-900"
          }`}
        >
          {notice.type === "success" ? (
            <CheckCircle2 className="h-5 w-5 shrink-0 text-emerald-600 mt-0.5" />
          ) : (
            <AlertCircle className="h-5 w-5 shrink-0 text-red-600 mt-0.5" />
          )}
          <div className="flex-1 text-xs font-medium leading-relaxed">
            {notice.message}
          </div>
          <button
            type="button"
            onClick={() => setNotice(null)}
            className="text-xs font-bold opacity-60 hover:opacity-100"
          >
            ✕
          </button>
        </div>
      )}

      {/* Reconciliation Invariant Banner */}
      {ledger?.reconciliation && (
        <div className="mb-6 rounded-2xl bg-white p-5 shadow-sm ring-1 ring-zinc-200/80">
          <div className="flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
            <div className="flex items-start sm:items-center gap-3">
              <div
                className={`flex h-10 w-10 shrink-0 items-center justify-center rounded-xl ${
                  ledger.reconciliation.isReconciled
                    ? "bg-emerald-100 text-emerald-700"
                    : "bg-red-100 text-red-700"
                }`}
              >
                {ledger.reconciliation.isReconciled ? (
                  <ShieldCheck className="h-6 w-6" />
                ) : (
                  <AlertTriangle className="h-6 w-6" />
                )}
              </div>
              <div>
                <div className="flex items-center gap-2">
                  <h2 className="text-sm font-bold text-zinc-900 sm:text-base">
                    Double-Entry Financial Invariant
                  </h2>
                  <span
                    className={`rounded-full px-2.5 py-0.5 text-[10px] font-bold uppercase tracking-wider ${
                      ledger.reconciliation.isReconciled
                        ? "bg-emerald-100 text-emerald-800"
                        : "bg-red-100 text-red-800"
                    }`}
                  >
                    {ledger.reconciliation.isReconciled ? "Balanced (0.00 Variance)" : "Variance Detected"}
                  </span>
                </div>
                <p className="mt-0.5 text-xs text-zinc-500">
                  {ledger.reconciliation.isReconciled
                    ? "Total customer payment inflows match platform equity, merchant escrow liabilities, and paid disbursements."
                    : `Discrepancy of GHS ${(ledger.reconciliation.varianceGhs ?? 0).toFixed(2)} (${ledger.reconciliation.variancePesewas ?? 0} pesewas) detected between ledger legs.`}
                </p>
              </div>
            </div>

            <div className="flex items-center gap-4 text-xs">
              <div className="rounded-lg bg-zinc-50 px-3 py-1.5 border border-zinc-200">
                <span className="text-zinc-500 block text-[10px] uppercase font-bold">As of Timestamp</span>
                <span className="font-semibold text-zinc-800">
                  {new Date(ledger.asOf || Date.now()).toLocaleTimeString()} · {new Date(ledger.asOf || Date.now()).toLocaleDateString()}
                </span>
              </div>
            </div>
          </div>
        </div>
      )}

      {/* 4 Core Accounting Quadrants */}
      {ledger?.inflow && ledger?.liabilities && ledger?.equity && ledger?.disbursements ? (
        <div className="mb-6 grid grid-cols-1 gap-4 sm:grid-cols-2 lg:grid-cols-4">
          {/* 1. Customer Gateway Inflows */}
          <div className="rounded-2xl bg-white p-5 shadow-sm ring-1 ring-zinc-200/80">
            <div className="flex items-center justify-between">
              <span className="text-xs font-bold uppercase tracking-wider text-zinc-500">
                Gateway Inflows
              </span>
              <div className="flex h-8 w-8 items-center justify-center rounded-lg bg-emerald-50 text-emerald-600">
                <ArrowUpRight className="h-4 w-4" />
              </div>
            </div>
            <p className="mt-3 text-2xl font-black text-zinc-900">
              {formatPrice(ledger.inflow.totalCustomerPaymentsGhs, "GHS")}
            </p>
            <p className="mt-1 text-xs text-zinc-500">
              {ledger.inflow.successfulPaymentsCount} successful transactions
            </p>
            <div className="mt-3 border-t border-zinc-100 pt-2 text-[11px] text-zinc-400">
              Integer: {ledger.inflow.totalCustomerPaymentsPesewas.toLocaleString()} pesewas
            </div>
          </div>

          {/* 2. Merchant Liabilities */}
          <div className="rounded-2xl bg-white p-5 shadow-sm ring-1 ring-zinc-200/80">
            <div className="flex items-center justify-between">
              <span className="text-xs font-bold uppercase tracking-wider text-zinc-500">
                Merchant Liabilities
              </span>
              <div className="flex h-8 w-8 items-center justify-center rounded-lg bg-amber-50 text-amber-600">
                <Building className="h-4 w-4" />
              </div>
            </div>
            <p className="mt-3 text-2xl font-black text-zinc-900">
              {formatPrice(ledger.liabilities.totalMerchantLiabilityGhs, "GHS")}
            </p>
            <div className="mt-2 space-y-1 text-xs">
              <div className="flex justify-between text-zinc-600">
                <span>In Escrow (Delivery pending):</span>
                <span className="font-semibold">{formatPrice(ledger.liabilities.vendorEscrowPendingGhs, "GHS")}</span>
              </div>
              <div className="flex justify-between text-zinc-600">
                <span>Ready for Payout:</span>
                <span className="font-semibold text-emerald-600">
                  {formatPrice(ledger.liabilities.vendorAvailablePayoutGhs, "GHS")}
                </span>
              </div>
            </div>
          </div>

          {/* 3. Platform Equity */}
          <div className="rounded-2xl bg-white p-5 shadow-sm ring-1 ring-zinc-200/80">
            <div className="flex items-center justify-between">
              <span className="text-xs font-bold uppercase tracking-wider text-zinc-500">
                Platform Commission
              </span>
              <div className="flex h-8 w-8 items-center justify-center rounded-lg bg-[#ff9900]/10 text-[#ff9900]">
                <TrendingUp className="h-4 w-4" />
              </div>
            </div>
            <p className="mt-3 text-2xl font-black text-zinc-900">
              {formatPrice(ledger.equity.totalCommissionGhs, "GHS")}
            </p>
            <div className="mt-2 space-y-1 text-xs">
              <div className="flex justify-between text-zinc-600">
                <span>Earned (Delivered):</span>
                <span className="font-semibold text-emerald-600">
                  {formatPrice(ledger.equity.earnedPlatformCommissionGhs, "GHS")}
                </span>
              </div>
              <div className="flex justify-between text-zinc-600">
                <span>Unearned (In-Flight):</span>
                <span className="font-semibold text-zinc-500">
                  {formatPrice(ledger.equity.potentialPlatformCommissionGhs, "GHS")}
                </span>
              </div>
            </div>
          </div>

          {/* 4. Disbursements & Refunds */}
          <div className="rounded-2xl bg-white p-5 shadow-sm ring-1 ring-zinc-200/80">
            <div className="flex items-center justify-between">
              <span className="text-xs font-bold uppercase tracking-wider text-zinc-500">
                Disbursements
              </span>
              <div className="flex h-8 w-8 items-center justify-center rounded-lg bg-blue-50 text-blue-600">
                <Receipt className="h-4 w-4" />
              </div>
            </div>
            <p className="mt-3 text-2xl font-black text-zinc-900">
              {formatPrice(ledger.disbursements.totalPaidOutGhs, "GHS")}
            </p>
            <div className="mt-2 space-y-1 text-xs">
              <div className="flex justify-between text-zinc-600">
                <span>MoMo Paid Out:</span>
                <span className="font-semibold">{ledger.disbursements.paidOutBatchesCount} batches</span>
              </div>
              <div className="flex justify-between text-zinc-600">
                <span>Refunded to Customers:</span>
                <span className="font-semibold text-red-600">
                  {formatPrice(ledger.disbursements.refundedGhs, "GHS")}
                </span>
              </div>
            </div>
          </div>
        </div>
      ) : (
        <div className="mb-6 grid grid-cols-1 gap-4 sm:grid-cols-4">
          {[1, 2, 3, 4].map((i) => (
            <div key={i} className="h-32 rounded-2xl bg-white p-5 animate-pulse" />
          ))}
        </div>
      )}

      {/* Payout Batches Management Section */}
      <div className="mb-8 rounded-2xl bg-white shadow-sm ring-1 ring-zinc-200/80 overflow-hidden">
        <div className="border-b border-zinc-100 p-5 sm:flex sm:items-center sm:justify-between">
          <div>
            <div className="flex items-center gap-2">
              <h3 className="font-bold text-zinc-900 sm:text-base">
                Automated MoMo Payout Batches
              </h3>
              <span className="rounded-full bg-zinc-100 px-2.5 py-0.5 text-xs font-bold text-zinc-600">
                {totalBatches} total
              </span>
            </div>
            <p className="mt-1 text-xs text-zinc-500">
              Settlements disbursed directly to vendor Mobile Money wallets (MTN, Telecel, AT) via Paystack Bulk Transfers.
            </p>
          </div>

          <div className="mt-3 sm:mt-0 flex items-center gap-2">
            <span className="text-[11px] font-semibold text-zinc-500 bg-zinc-50 px-2.5 py-1 rounded border border-zinc-200">
              Minimum Threshold: GHS 20.00
            </span>
          </div>
        </div>

        {/* Batches Table */}
        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs">
            <thead className="border-b border-zinc-100 bg-zinc-50/75 text-[11px] font-bold uppercase tracking-wider text-zinc-500">
              <tr>
                <th className="py-3.5 pl-5 pr-3">Batch Reference</th>
                <th className="px-3 py-3.5">Status</th>
                <th className="px-3 py-3.5">Amount (GHS)</th>
                <th className="px-3 py-3.5">Merchants</th>
                <th className="px-3 py-3.5">Orders</th>
                <th className="px-3 py-3.5">Created Date</th>
                <th className="px-3 py-3.5">Transfer Code</th>
                <th className="py-3.5 pl-3 pr-5 text-right">Actions</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-zinc-100 font-medium text-zinc-700">
              {batches.length > 0 ? (
                batches.map((batch) => {
                  const isExecuting = executingBatchId === batch.id;
                  return (
                    <tr key={batch.id} className="hover:bg-zinc-50/50 transition">
                      <td className="py-3.5 pl-5 pr-3 font-mono font-bold text-zinc-900">
                        {batch.batchReference}
                      </td>
                      <td className="px-3 py-3.5">
                        <span
                          className={`inline-flex items-center gap-1.5 rounded-full px-2.5 py-0.5 text-[10px] font-bold uppercase tracking-wider ${
                            batch.status === "PAID"
                              ? "bg-emerald-100 text-emerald-800"
                              : batch.status === "PROCESSING"
                              ? "bg-blue-100 text-blue-800"
                              : batch.status === "FAILED"
                              ? "bg-red-100 text-red-800"
                              : "bg-amber-100 text-amber-800"
                          }`}
                        >
                          {batch.status === "PROCESSING" && (
                            <Loader2 className="h-2.5 w-2.5 animate-spin" />
                          )}
                          {batch.status}
                        </span>
                      </td>
                      <td className="px-3 py-3.5 font-bold text-zinc-900">
                        {formatPrice(Number(batch.totalAmount), batch.currency || "GHS")}
                      </td>
                      <td className="px-3 py-3.5 text-zinc-600">
                        {batch.totalVendors} merchants
                      </td>
                      <td className="px-3 py-3.5 text-zinc-600">
                        {batch.totalOrders} orders
                      </td>
                      <td className="px-3 py-3.5 text-zinc-500">
                        {new Date(batch.createdAt).toLocaleDateString()} ·{" "}
                        {new Date(batch.createdAt).toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" })}
                      </td>
                      <td className="px-3 py-3.5 font-mono text-zinc-500">
                        {batch.paystackTransferCode || "—"}
                      </td>
                      <td className="py-3.5 pl-3 pr-5 text-right">
                        {batch.status === "PENDING" && isSuperAdmin ? (
                          <button
                            type="button"
                            onClick={() => handleExecuteBatch(batch.id)}
                            disabled={isExecuting}
                            className="inline-flex items-center gap-1.5 rounded-lg bg-zinc-900 px-3 py-1.5 text-xs font-bold text-white shadow transition hover:bg-zinc-800 active:scale-95 disabled:opacity-60"
                          >
                            {isExecuting ? (
                              <Loader2 className="h-3 w-3 animate-spin" />
                            ) : (
                              <Send className="h-3 w-3 text-[#ff9900]" />
                            )}
                            <span>Disburse MoMo</span>
                          </button>
                        ) : (
                          <button
                            type="button"
                            onClick={() => setSelectedBatch(batch)}
                            className="text-xs font-semibold text-zinc-500 hover:text-zinc-900 transition"
                          >
                            View Details
                          </button>
                        )}
                      </td>
                    </tr>
                  );
                })
              ) : (
                <tr>
                  <td colSpan={8} className="py-12 text-center text-xs text-zinc-400">
                    No payout batches recorded yet. Click &quot;Generate Payout Batch&quot; to aggregate cleared orders.
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>
      </div>

      {/* Daily Accounting Ledger Breakdown */}
      {ledger && ledger.dailyBreakdown && ledger.dailyBreakdown.length > 0 && (
        <div className="rounded-2xl bg-white shadow-sm ring-1 ring-zinc-200/80 overflow-hidden">
          <div className="border-b border-zinc-100 p-5">
            <h3 className="font-bold text-zinc-900 sm:text-base">
              Daily Ledger Activity &amp; Cashflow
            </h3>
            <p className="mt-0.5 text-xs text-zinc-500">
              Synchronized daily gateway inflows, vendor escrow additions, earned commissions, and disbursed transfers.
            </p>
          </div>

          <div className="overflow-x-auto">
            <table className="w-full text-left text-xs">
              <thead className="border-b border-zinc-100 bg-zinc-50/75 text-[11px] font-bold uppercase tracking-wider text-zinc-500">
                <tr>
                  <th className="py-3.5 pl-5 pr-3">Date</th>
                  <th className="px-3 py-3.5">Customer Inflows</th>
                  <th className="px-3 py-3.5">Vendor Escrow Incurred</th>
                  <th className="px-3 py-3.5">Earned Commission</th>
                  <th className="py-3.5 pl-3 pr-5 text-right">MoMo Disbursed</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-zinc-100 font-medium text-zinc-700">
                {ledger.dailyBreakdown.map((row) => (
                  <tr key={row.date} className="hover:bg-zinc-50/50 transition">
                    <td className="py-3 pl-5 pr-3 font-semibold text-zinc-900">
                      {row.date}
                    </td>
                    <td className="px-3 py-3 font-bold text-emerald-700">
                      {formatPrice(row.customerPaymentsGhs, "GHS")}
                    </td>
                    <td className="px-3 py-3 text-amber-700">
                      {formatPrice(row.vendorLiabilitiesGhs, "GHS")}
                    </td>
                    <td className="px-3 py-3 text-[#ff9900] font-semibold">
                      {formatPrice(row.earnedCommissionGhs, "GHS")}
                    </td>
                    <td className="py-3 pl-3 pr-5 text-right font-semibold text-zinc-800">
                      {formatPrice(row.payoutDisbursementsGhs, "GHS")}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      )}

      {/* Batch Details Modal */}
      {selectedBatch && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/60 backdrop-blur-xs animate-in fade-in duration-200">
          <div className="relative w-full max-w-lg rounded-2xl bg-white p-6 shadow-2xl ring-1 ring-zinc-200">
            <div className="flex items-center justify-between border-b border-zinc-100 pb-4">
              <div>
                <h4 className="font-bold text-zinc-900">Batch {selectedBatch.batchReference}</h4>
                <p className="text-xs text-zinc-500">
                  Created {new Date(selectedBatch.createdAt).toLocaleString()}
                </p>
              </div>
              <button
                type="button"
                onClick={() => setSelectedBatch(null)}
                className="rounded-lg p-1.5 text-zinc-400 hover:bg-zinc-100 hover:text-zinc-700"
              >
                ✕
              </button>
            </div>

            <div className="mt-4 space-y-3 text-xs">
              <div className="flex justify-between border-b border-zinc-50 pb-2">
                <span className="text-zinc-500">Disbursement Status</span>
                <span className="font-bold text-zinc-900">{selectedBatch.status}</span>
              </div>
              <div className="flex justify-between border-b border-zinc-50 pb-2">
                <span className="text-zinc-500">Total Settlement</span>
                <span className="font-bold text-zinc-900">
                  {formatPrice(Number(selectedBatch.totalAmount), selectedBatch.currency)}
                </span>
              </div>
              <div className="flex justify-between border-b border-zinc-50 pb-2">
                <span className="text-zinc-500">Recipients Count</span>
                <span className="font-semibold text-zinc-800">{selectedBatch.totalVendors} merchants</span>
              </div>
              <div className="flex justify-between border-b border-zinc-50 pb-2">
                <span className="text-zinc-500">Cleared Orders Linked</span>
                <span className="font-semibold text-zinc-800">{selectedBatch.totalOrders} vendor orders</span>
              </div>
              {selectedBatch.paystackTransferCode && (
                <div className="flex justify-between border-b border-zinc-50 pb-2">
                  <span className="text-zinc-500">Paystack Transfer Code</span>
                  <span className="font-mono font-semibold text-zinc-800">
                    {selectedBatch.paystackTransferCode}
                  </span>
                </div>
              )}
              {selectedBatch.notes && (
                <div className="pt-2 text-zinc-600 bg-zinc-50 p-3 rounded-lg border border-zinc-100">
                  <span className="font-bold text-zinc-700 block mb-1">Batch Notes:</span>
                  {selectedBatch.notes}
                </div>
              )}
            </div>

            <div className="mt-6 flex justify-end">
              <button
                type="button"
                onClick={() => setSelectedBatch(null)}
                className="rounded-lg bg-zinc-100 px-4 py-2 text-xs font-semibold text-zinc-700 hover:bg-zinc-200"
              >
                Close
              </button>
            </div>
          </div>
        </div>
      )}
    </AdminLayout>
  );
}
